"use client";

import * as React from "react";
import Link from "next/link";
import { useRouter } from "next/navigation";
import { api, useCountries } from "@/lib/api";
import { Container, PageHeader } from "@/components/shell/page";
import { SyntheticBadge } from "@/components/shell/synthetic-badge";
import { DataTable } from "@/components/data-table";
import { ErrorState, EmptyState, PageSkeleton } from "@/components/states";
import { Button } from "@/components/ui/button";
import { Modal } from "@/components/ui/sheet";
import { Input, Label } from "@/components/ui/misc";
import { StressBadge } from "@/components/ui/badge";
import { Breadcrumb } from "@/components/ui/breadcrumb";
import type { ColumnSpec } from "@/lib/csv";
import type { CountrySummary } from "@/lib/types";

export default function AssessmentsPage() {
  const { data, error, mutate, isLoading } = useCountries();
  const [cloneFrom, setCloneFrom] = React.useState<CountrySummary | null>(null);
  const synthetic = data?.filter((c) => c.kind === "synthetic") ?? [];
  const custom = data?.filter((c) => c.kind === "custom") ?? [];

  const columns = React.useMemo<ColumnSpec<CountrySummary>[]>(
    () => [
      {
        key: "name",
        header: "Country",
        value: (c) => c.name,
        cell: (c) => (
          <span className="flex flex-col py-1">
            <Link href={`/countries/${c.id}`} className="link font-medium">
              {c.name}
            </Link>
            <span className="t-caption text-ink-subtle">{c.tagline}</span>
          </span>
        ),
      },
      { key: "kind", header: "Data", value: (c) => (c.kind === "synthetic" ? "Synthetic" : "Custom"), cell: (c) => (c.kind === "synthetic" ? <SyntheticBadge short /> : "Custom") },
      { key: "years", header: "Years", value: (c) => `${c.years[0]}–${c.latest.year}` },
      { key: "fsfsi", header: "Stress index", numeric: true, value: (c) => c.latest.fsfsi, format: (v) => v.toFixed(2) },
      { key: "class", header: "Stress class", value: (c) => c.latest.stress_class, cell: (c) => <StressBadge cls={c.latest.stress_class} /> },
      { key: "eff", header: "Efficiency", numeric: true, value: (c) => c.latest.efficiency, format: (v) => v.toFixed(2) },
      { key: "ind", header: "Indicators", numeric: true, value: (c) => c.n_indicators },
      {
        key: "actions",
        header: "Actions",
        value: () => "",
        cell: (c) => (
          <span className="flex gap-1">
            <Button variant="quiet" size="sm" onClick={() => setCloneFrom(c)}>
              Clone
            </Button>
            {c.kind === "custom" ? (
              <Button
                variant="quiet"
                size="sm"
                onClick={async () => {
                  if (!confirm(`Delete ${c.name}? This cannot be undone.`)) return;
                  await api.deleteCountry(c.id);
                  void mutate();
                }}
              >
                Delete
              </Button>
            ) : null}
          </span>
        ),
      },
    ],
    [mutate],
  );

  return (
    <div>
      <PageHeader
        eyebrow={<Breadcrumb items={[{ label: "Home", href: "/" }, { label: "Assessments" }]} />}
        title="Assessments"
        description="Open a country to see its assessment for any fiscal year, weighting and scenario. The demonstration countries are synthetic archetypes: their names, budgets and indicator values are generated by a seeded model."
        actions={
          <Button asChild variant="secondary">
            <Link href="/builder">Build for a country</Link>
          </Button>
        }
      />
      <Container className="space-y-12 py-10">
        {error ? (
          <ErrorState error={error} onRetry={() => void mutate()} />
        ) : isLoading || !data ? (
          <PageSkeleton />
        ) : (
          <>
            <section aria-labelledby="demo-h">
              <h2 id="demo-h" className="t-h2">
                Demonstration countries
              </h2>
              <p className="mt-1 max-w-[68ch] t-ui text-ink-muted">Latest fiscal year, hybrid weights, normal operations.</p>
              <DataTable
                className="mt-4"
                rows={synthetic}
                columns={columns}
                caption="Synthetic demonstration countries, latest fiscal year"
                filename="fsfsi-demonstration-countries"
                rowKey={(c) => c.id}
              />
            </section>
            <section aria-labelledby="custom-h">
              <h2 id="custom-h" className="t-h2">
                Your countries
              </h2>
              {custom.length ? (
                <DataTable
                  className="mt-4"
                  rows={custom}
                  columns={columns}
                  caption="Countries built on this machine"
                  filename="fsfsi-custom-countries"
                  rowKey={(c) => c.id}
                />
              ) : (
                <EmptyState title="No countries of your own yet" className="mt-4">
                  Build one from your indicators and budget lines with{" "}
                  <Link href="/builder" className="link">
                    Build for a country
                  </Link>
                  , or clone a demonstration country above to start from its data.
                </EmptyState>
              )}
            </section>
          </>
        )}
      </Container>
      <CloneDialog from={cloneFrom} onClose={() => setCloneFrom(null)} />
    </div>
  );
}

function CloneDialog({ from, onClose }: { from: CountrySummary | null; onClose: () => void }) {
  const router = useRouter();
  const [name, setName] = React.useState("");
  const [busy, setBusy] = React.useState(false);
  const [err, setErr] = React.useState<unknown>(null);
  return (
    <Modal
      open={!!from}
      onOpenChange={(o) => {
        if (!o) {
          onClose();
          setName("");
          setErr(null);
        }
      }}
      title={`Clone ${from?.name ?? ""}`}
      description="An editable copy with the same data, saved on this machine."
    >
      <form
        onSubmit={async (e) => {
          e.preventDefault();
          if (!from || !name.trim()) return;
          setBusy(true);
          setErr(null);
          try {
            const p = await api.cloneCountry(from.id, name.trim());
            router.push(`/countries/${p.id}`);
          } catch (e2) {
            setErr(e2);
          } finally {
            setBusy(false);
          }
        }}
      >
        <Label htmlFor="clone-name">Name of the new country</Label>
        <Input id="clone-name" autoFocus value={name} onChange={(e) => setName(e.target.value)} placeholder="For example, Northshire" />
        {err ? <p className="mt-2 t-ui text-alert">{err instanceof Error ? err.message : String(err)}</p> : null}
        <div className="mt-5 flex justify-end gap-2">
          <Button type="button" variant="quiet" onClick={onClose}>
            Cancel
          </Button>
          <Button type="submit" disabled={busy || !name.trim()}>
            {busy ? "Cloning" : "Clone"}
          </Button>
        </div>
      </form>
    </Modal>
  );
}
