function Evidence() {
  const { data: countries, error: cErr } = useCountries();
  const { data: health } = useHealth();
  const demo = countries?.find((c) => c.id === "aurelia") ?? countries?.find((c) => c.kind === "synthetic");
  const { data: a, error } = useAssessment(demo?.id, {});
  const err = cErr ?? error;
  const rows = a ? diagnosisRows(a.diagnosis_summary) : [];
  const unf = a?.diagnosis_summary.find((d) => d.diagnosis === "unfunded_gap");

  return (
    <Section
      id="evidence"
      title="Evidence from a demonstration assessment"
      lead={demo ? `Applied to ${demo.name}, a synthetic archetype (${demo.tagline.toLowerCase()}), the chart compares where the budget goes with where financing stress remains.` : "Applied to a synthetic archetype country, the chart compares where the budget goes with where financing stress remains."}
    >
      {err ? (
        <ErrorState error={err} />
      ) : !a || !demo ? (
        <div className="rounded-[4px] border border-rule bg-surface p-5">
          <ChartSkeleton height={300} />
        </div>
      ) : (
        <FigureSourceProvider
          source={`FSFSI assessment engine v${health?.version ?? "1"}; synthetic demonstration data for ${demo.name}, fiscal year ${a.year}, hybrid weights, normal operations.`}
          filePrefix={`${demo.id}-${a.year}`}
        >
          <div className="mb-3 flex flex-wrap items-center gap-3">
            <SyntheticBadge />
            <span className="t-ui text-ink-muted">
              {demo.name}, fiscal year {a.year}
            </span>
          </div>
          <Figure
            title={`Unfunded gaps receive ${fmtPct(unf?.envelope_share)} of the budget and carry ${fmtPct(unf?.stress_share)} of financing stress`}
            subtitle={`Share of the budget envelope and of total stress, by diagnosis class (%), ${demo.name}, fiscal year ${a.year}`}
            notes="Shares of the budget and of stress each sum to 100%. Diagnosis uses the country's own coverage and gap cut points."
            data={{ columns: diagnosisColumns, rows, filename: "budget-and-stress-by-diagnosis" }}
            className="max-w-[880px]"
          >
            <DiagnosisBars rows={rows} />
          </Figure>
          <p className="mt-4 t-ui">
            <Link href={`/countries/${demo.id}`} className="link">
              Open the full assessment for {demo.name}
            </Link>
          </p>
        </FigureSourceProvider>
      )}
    </Section>
  );
}
